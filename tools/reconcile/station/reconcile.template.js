// Weigh-station reconcile, run inside the station's own web page.
//
// Open the station in Chrome (http://STATION/), press F12, Console tab, paste
// this whole file, press Enter. It CHECKS ONLY and prints what it would do.
// Then type   reconcile.apply()   and press Enter to do it.
//
// What apply() does, in order, through the station's own pages:
//   1. downloads a backup (log + config) to this PC, before anything changes
//   2. removes the test vendors' products and spools (fetches the log, drops
//      their lines, loads it back through Backup -> Restore). Anything weighed
//      in those few seconds would be lost, so do it with no one at the scale.
//   3. merges duplicate products (Administration -> Repair)
//   4. renames products (each product's edit page; every spool of it follows,
//      and each tag on its next placement)
//   5. points Stock List items at the product the lab orders (PLA+ instead of
//      PLA Basic; created from the eSUN catalogue if missing) and sets which
//      products count toward each item as substitutes (Stock List edit)
//   6. makes Stock List labels follow their products, drops test vendors from
//      the picklist (Backup -> Restore config)
//   7. checks the result and downloads an "after" backup
// Every change first checks the station still has what the decisions were made
// on, and is skipped and reported if not. Running it again changes nothing.
// Generated by tools/reconcile/build_station_kit.py; do not edit by hand.
(() => {
  const KIT = /*KIT*/null/*END*/;

  const out = (...a) => console.log("%c" + a.join(" "), "font-family:monospace");
  const head = (s) => console.log("%c" + s, "font-weight:bold;font-size:1.1em;margin-top:.6em");
  const bad = (s) => console.log("%c" + s, "color:#c00;font-weight:bold");
  const good = (s) => console.log("%c" + s, "color:#080;font-weight:bold");

  async function getJ(p) { const r = await fetch(p, { cache: "no-store" }); if (!r.ok) throw new Error(`${p}: HTTP ${r.status}`); return r.json(); }
  async function getT(p) { const r = await fetch(p, { cache: "no-store" }); if (!r.ok) throw new Error(`${p}: HTTP ${r.status}`); return r.text(); }
  async function post(p, fields) { return fetch(p, { method: "POST", body: new URLSearchParams(fields) }); }
  async function upload(p, name, text) {
    const fd = new FormData();
    fd.append("file", new Blob([text], { type: "application/octet-stream" }), name);
    return fetch(p, { method: "POST", body: fd });
  }
  function save(name, text) {
    if (window.RECONCILE_NO_DOWNLOAD) { out(`(test: not downloading ${name}, ${text.length} bytes)`); return; }
    const a = document.createElement("a");
    a.href = URL.createObjectURL(new Blob([text], { type: "application/octet-stream" }));
    a.download = name; document.body.appendChild(a); a.click(); a.remove();
  }
  const stamp = () => new Date().toISOString().slice(0, 16).replace(/[:T]/g, "-");
  const byId = (list) => Object.fromEntries(list.map((p) => [p.id, p]));

  // ---- the Stock List step (tools/reconcile/stockplan.py), by product name
  const SK = KIT.stock;
  const byName = (P, name) => { const h = Object.values(P).filter((p) => p.vendor === SK.vendor && p.material === name); return h.length === 1 ? h[0] : null; };
  const itemOf = (rows, P, name) => { const p = byName(P, name); const h = rows.filter((s) => p && s.product === p.id); return [h.length === 1 ? h[0] : null, p]; };
  function stockUpdate(s, extra, subs) {
    const f = { id: s.id, min_spools: s.min_spools || 0, min_grams: s.min_grams || 0, gtin: s.gtin || "",
                pack_qty: s.pack_qty || 1, subs: subs.join(",") };
    return post("/api/stock/update", Object.assign(f, extra));
  }
  // What step 5 would do, given the products as they will be by then (P with
  // the merges and renames applied: before them, a Basic product and its PLA+
  // look-alike can share a name).
  function stockPlan(P, rows) {
    const todo = { relink: [], subs: [], skip: [] };
    const named = (n) => byName(P, n);
    const itemFor = (n) => { const p = named(n); const h = rows.filter((s) => p && s.product === p.id); return h.length === 1 ? h[0] : null; };
    const relinked = {};
    for (const r of SK.relink) {
      const s = itemFor(r.old);
      if (!s) { if (!itemFor(r.new)) todo.skip.push(`Stock List "${r.old}" -> "${r.new}": no single item linked to "${r.old}"`); continue; }
      relinked[r.new] = s;
      todo.relink.push(Object.assign({ row: s, oldP: named(r.old), newP: named(r.new) }, r));
    }
    for (const x of SK.subs) {
      const s = itemFor(x.item) || relinked[x.item];
      if (!s) { todo.skip.push(`substitutes for "${x.item}": no single Stock List item for it`); continue; }
      const want = x.products.map((n) => named(n)).filter(Boolean).map((p) => p.id);
      const missing = x.products.filter((n) => !named(n));
      for (const n of missing) todo.skip.push(`"${n}" counts toward "${x.item}": no such product`);
      const have = (s.subs || []).filter(Boolean);
      if (want.some((id) => !have.includes(id))) todo.subs.push({ item: x.item, products: x.products });
    }
    return todo;
  }

  // ---- the test vendors' lines in the log (same rule as remove_vendor.py)
  function testVendorLines(logText) {
    const lines = logText.split("\n").filter((l) => l.trim());
    const ev = lines.map((l) => JSON.parse(l));
    const vendors = new Set(KIT.removeVendors.map((v) => v.toLowerCase()));
    const prods = new Set(ev.filter((e) => e.ev === "product" && vendors.has((e.vendor || "").toLowerCase())).map((e) => e.prod));
    const uuids = new Set(ev.filter((e) => e.uuid && prods.has(e.prod)).map((e) => e.uuid));
    const other = ev.filter((e) => uuids.has(e.uuid) && e.prod && !prods.has(e.prod));
    const drop = ev.map((e) => (e.ev === "product" && prods.has(e.prod)) || uuids.has(e.uuid));
    return { lines, prods: [...prods].sort((a, b) => a - b), spools: [...new Set(ev.filter((e, i) => drop[i] && e.spool).map((e) => e.spool))].sort((a, b) => a - b),
             drop, other: other.map((e) => `spool ${e.spool} is also product #${e.prod}`) };
  }

  async function plan() {
    const st = await getJ("/api/status");
    const P = byId(await getJ("/api/products"));
    const plan = { ok: true, status: st, merges: [], renames: [], skip: [], done: [], test: null };
    head("Weigh-station reconcile: CHECK ONLY (nothing is changed)");
    out(`station: ${location.host}   firmware: ${st.build_version}`);
    if (!String(st.build_version).includes(KIT.build)) {
      bad(`This station runs ${st.build_version}, but these decisions are for firmware ${KIT.build}. Flash the kit's firmware first.`);
      plan.ok = false; return plan;
    }
    // the eSUN catalogue (loaded separately, on Administration)
    try {
      const c = await fetch("/catalogue.json", { cache: "no-store" });
      const cj = c.ok ? await c.json() : null;
      if (!cj) bad(`eSUN US catalogue: not loaded. Load station-catalogue.json on Administration -> eSUN US catalogue (step 3 of the instructions).`);
      else if (KIT.catalogue && (cj.date !== KIT.catalogue.date || cj.count !== KIT.catalogue.count))
        bad(`eSUN US catalogue: the station has ${cj.count} items from ${cj.date}, this kit's is ${KIT.catalogue.count} from ${KIT.catalogue.date}. Load the kit's station-catalogue.json.`);
      else out(`eSUN US catalogue: loaded, ${cj.count} items from ${cj.date}`);
    } catch (e) { bad("eSUN US catalogue: couldn't check (" + e.message + ")"); }
    // test vendors
    const tv = testVendorLines(await getT("/export"));
    plan.test = tv;
    if (tv.other.length) { bad("Test vendor spools are linked to real products, not removing: " + tv.other.join("; ")); plan.ok = false; }
    else if (tv.prods.length) out(`test vendors ${KIT.removeVendors.join(", ")}: remove products #${tv.prods.join(", #")}, spools #${tv.spools.join(", #")} (${tv.drop.filter(Boolean).length} log lines)`);
    else out(`test vendors ${KIT.removeVendors.join(", ")}: nothing left to remove`);
    // merges
    const losers = new Set();
    for (const m of KIT.merges) {
      const what = `merge #${m.from} into #${m.into}`;
      losers.add(m.from);
      const a = P[m.from], b = P[m.into];
      if (!a && b) { plan.done.push(what); continue; }
      if (!a || !b) { plan.skip.push(`${what}: product missing`); continue; }
      if (a.material !== m.fromName) { plan.skip.push(`${what}: #${m.from} is now "${a.material}", expected "${m.fromName}"`); continue; }
      plan.merges.push(m);
    }
    // renames
    for (const r of KIT.renames) {
      const what = `#${r.id} "${r.vendorNow} ${r.nameNow}" -> "${r.vendor} ${r.name}"`;
      const p = P[r.id];
      if (losers.has(r.id)) { plan.done.push(what + " (merged away)"); continue; }
      if (!p) { plan.skip.push(`${what}: product missing`); continue; }
      if (p.vendor === r.vendor && p.material === r.name) { plan.done.push(what); continue; }
      if (p.vendor !== r.vendorNow || p.material !== r.nameNow) { plan.skip.push(`${what}: station has "${p.vendor} ${p.material}"`); continue; }
      plan.renames.push(r);
    }
    const Pn = {};
    for (const [id, p] of Object.entries(P)) if (!losers.has(+id)) Pn[id] = Object.assign({}, p);
    for (const r of plan.renames) if (Pn[r.id]) { Pn[r.id].vendor = r.vendor; Pn[r.id].material = r.name; }
    const sp = stockPlan(Pn, (await getJ("/config/export"))["stock-items"]);
    plan.stock = sp; plan.skip.push(...sp.skip);
    out(`merges to do: ${plan.merges.length}   renames to do: ${plan.renames.length}   Stock List items to repoint: ${sp.relink.length}   substitute changes: ${sp.subs.length}   already done: ${plan.done.length}   skipped: ${plan.skip.length}`);
    if (plan.merges.length) console.table(plan.merges.map((m) => ({ merge: `#${m.from} ${m.fromName}`, into: `#${m.into}` })));
    if (plan.renames.length) console.table(plan.renames.map((r) => ({ product: r.id, now: `${r.vendorNow} ${r.nameNow}`, becomes: `${r.vendor} ${r.name}` })));
    if (sp.relink.length) console.table(sp.relink.map((r) => ({ "Stock List item": r.old, "points at": r.new, product: r.newP ? `#${r.newP.id}` : "new, from the eSUN catalogue" })));
    if (sp.subs.length) console.table(sp.subs.map((x) => ({ "Stock List item": x.item, "substitutes": x.products.join(", ") })));
    for (const s of plan.skip) bad("SKIP " + s);
    return plan;
  }

  async function verify() {
    head("Checking the result");
    const P = byId(await getJ("/api/products"));
    const raw = await getJ("/api/spools"); const S = raw.spools || raw;
    const cfg = await getJ("/config/export");
    const fail = [];
    const merged = new Set(KIT.merges.map((m) => m.from));
    for (const m of KIT.merges) if (P[m.from]) fail.push(`#${m.from} should be merged into #${m.into}`);
    for (const r of KIT.renames) {
      const p = P[r.id];
      if (merged.has(r.id) || !p) continue;
      if (p.vendor !== r.vendor || p.material !== r.name) {
        if (p.vendor === r.vendorNow && p.material === r.nameNow) fail.push(`#${r.id} still "${p.vendor} ${p.material}"`);
        else out(`#${r.id} is "${p.vendor} ${p.material}" (changed on the station; left alone)`);
      }
    }
    for (const s of S) { const p = P[s.product]; if (p && (p.vendor !== s.vendor || p.material !== s.material)) fail.push(`spool #${s.spool} reads "${s.vendor} ${s.material}", its product "${p.vendor} ${p.material}"`); }
    for (const s of cfg["stock-items"]) {
      const p = P[s.product];
      if (merged.has(s.product)) fail.push(`Stock List #${s.id} still links merged #${s.product}`);
      else if (p && (s.vendor !== p.vendor || s.material !== p.material)) fail.push(`Stock List #${s.id} reads "${s.vendor} ${s.material}"`);
    }
    const rows = cfg["stock-items"];
    for (const r of SK.relink) {
      if (itemOf(rows, P, r.old)[0]) fail.push(`Stock List item "${r.old}" still points at it, not "${r.new}"`);
      else if (!itemOf(rows, P, r.new)[0]) fail.push(`no Stock List item points at "${r.new}"`);
    }
    for (const x of SK.subs) {
      const [s] = itemOf(rows, P, x.item);
      if (!s) { fail.push(`no Stock List item for "${x.item}"`); continue; }
      for (const n of x.products) { const p = byName(P, n); if (!p || !(s.subs || []).includes(p.id)) fail.push(`"${n}" does not count toward "${x.item}"`); }
    }
    const tv = new Set(KIT.removeVendors.map((v) => v.toLowerCase()));
    if (Object.values(P).some((p) => tv.has(p.vendor.toLowerCase()))) fail.push("test vendor products still present");
    if (cfg.vendors.some((v) => tv.has(v.toLowerCase()))) fail.push("test vendor still in the picklist");
    out(`products ${Object.keys(P).length}, spools ${S.length} (${S.filter((s) => !s.retired).length} on the shelf), Stock List ${cfg["stock-items"].length}`);
    if (fail.length) { bad("PROBLEMS:"); fail.forEach((f) => bad("  " + f)); } else good("Result checks out.");
    return fail;
  }

  async function apply() {
    const p = await plan();
    if (!p.ok) { bad("Not applying. Fix the problem above first."); return; }
    head("Applying");
    // 1. backup first
    const t0 = stamp();
    save(`weighstation-${t0}-before-reconcile-log.ndjson`, await getT("/export"));
    save(`weighstation-${t0}-before-reconcile-config.json`, await getT("/config/export"));
    out("backup downloaded (check your Downloads folder: two files)");
    // 2. test vendors: re-read the log now, so nothing weighed since the check is lost
    const tv = testVendorLines(await getT("/export"));
    if (tv.other.length) { bad("Test vendor spools linked to real products; stopping."); return; }
    if (tv.prods.length) {
      const kept = tv.lines.filter((l, i) => !tv.drop[i]).join("\n") + "\n";
      const r = await upload("/import", "events.ndjson", kept);
      if (!r.ok) { bad(`Removing test vendors failed: HTTP ${r.status} ${await r.text()}. Stopping; nothing else was changed.`); return; }
      out(`removed test vendors: products #${tv.prods.join(", #")}, spools #${tv.spools.join(", #")}`);
    }
    // 3. merges
    for (const m of p.merges) {
      const r = await post("/api/repair/merge", { a: m.from, b: m.into, into: m.into });
      if (r.ok && /merged=/.test(r.url)) out(`OK   merge #${m.from} into #${m.into}`); else bad(`FAIL merge #${m.from} into #${m.into}: HTTP ${r.status}`);
    }
    // 4. renames (current colour, diameter, tare and weight are sent back unchanged; the barcode field is left out, so it is kept)
    const P = byId(await getJ("/api/products"));
    for (const r of p.renames) {
      const q = P[r.id];
      if (!q) { bad(`SKIP #${r.id}: gone`); continue; }
      let abbr = q.abbr;
      for (const [line, a] of Object.entries(KIT.abbrBack)) if (r.name.startsWith(line + " ") && abbr !== a) abbr = a;
      const f = { id: r.id, vendor: r.vendor, material: r.name, abbr, dia: q.diameter_mm, empty_g: q.empty_g, nom_g: q.nominal_g };
      if (q.color === null) f.nocolor = "1"; else f.color = "#" + q.color;
      const res = await post("/api/product", f);
      if (res.ok) out(`OK   #${r.id} -> ${r.vendor} ${r.name}` + (abbr !== q.abbr ? `  (short code ${q.abbr} -> ${abbr})` : ""));
      else bad(`FAIL #${r.id}: HTTP ${res.status} ${await res.text()}`);
    }
    // 5. Stock List: repoint items, then substitutes (the station checks the rules)
    {
      let P3 = byId(await getJ("/api/products"));
      let rows = (await getJ("/config/export"))["stock-items"];
      for (const r of SK.relink) {
        const [s, old] = itemOf(rows, P3, r.old);
        if (!s) { if (!itemOf(rows, P3, r.new)[0]) bad(`SKIP Stock List "${r.old}": no single item linked to it`); continue; }
        const nw = byName(P3, r.new);
        const extra = nw ? { product: nw.id }
                         : Object.assign({}, r.cat, { source: "catalog", product: 0, empty_g: old.empty_g > 0 ? old.empty_g : SK.defaultTare });
        extra.gtin = "";   // the item's own barcode was the old product's
        const res = await stockUpdate(s, extra, (s.subs || []).filter(Boolean).concat([old.id]));
        if (res.ok) out(`OK   Stock List "${r.old}" -> "${r.new}"` + (nw ? "" : " (new product from the eSUN catalogue)"));
        else bad(`FAIL Stock List "${r.old}": HTTP ${res.status} ${await res.text()}`);
      }
      P3 = byId(await getJ("/api/products"));
      rows = (await getJ("/config/export"))["stock-items"];
      for (const x of SK.subs) {
        const [s] = itemOf(rows, P3, x.item);
        if (!s) { bad(`SKIP substitutes for "${x.item}": no single Stock List item`); continue; }
        const have = (s.subs || []).filter(Boolean), want = have.slice();
        for (const n of x.products) { const p = byName(P3, n); if (!p) { bad(`SKIP "${n}": no such product`); continue; } if (!want.includes(p.id) && p.id !== s.product) want.push(p.id); }
        if (want.length === have.length) continue;
        const res = await stockUpdate(s, { product: s.product }, want);
        if (res.ok) out(`OK   substitutes for "${x.item}": ${x.products.join(", ")}`);
        else bad(`FAIL substitutes for "${x.item}": HTTP ${res.status} ${await res.text()}`);
      }
    }
    // 6. Stock List labels and the vendor picklist, in one config restore
    const P2 = byId(await getJ("/api/products"));
    const cfg = await getJ("/config/export");
    let n = 0;
    for (const s of cfg["stock-items"]) {
      const q = P2[s.product];
      if (q && (s.vendor !== q.vendor || s.material !== q.material || (s.color || "") !== "")) { s.vendor = q.vendor; s.material = q.material; s.color = ""; n++; }
    }
    const tvset = new Set(KIT.removeVendors.map((v) => v.toLowerCase()));
    const before = cfg.vendors.length;
    cfg.vendors = cfg.vendors.filter((v) => !tvset.has(v.toLowerCase()));
    if (n || cfg.vendors.length !== before) {
      const r = await upload("/config/import", "config.json", JSON.stringify(cfg));
      if (r.ok) out(`OK   Stock List labels (${n} items)` + (cfg.vendors.length !== before ? ", test vendors removed from the picklist" : ""));
      else bad(`FAIL config: HTTP ${r.status} ${await r.text()}`);
    }
    // 7. check, then the after backup
    const fail = await verify();
    const t1 = stamp();
    save(`weighstation-${t1}-after-reconcile-log.ndjson`, await getT("/export"));
    save(`weighstation-${t1}-after-reconcile-config.json`, await getT("/config/export"));
    out("after backup downloaded (two more files)");
    if (!fail.length) good("Done. Running reconcile.apply() again would change nothing.");
    return fail;
  }

  window.reconcile = { plan, apply, verify, kit: KIT };
  plan().then((p) => {
    if (!p.ok) return;
    if (p.merges.length || p.renames.length || p.stock.relink.length || p.stock.subs.length || (p.test && p.test.prods.length)) good("Checks passed. To apply, type:   reconcile.apply()   and press Enter.");
    else good("Nothing to do: this station is already reconciled.");
  }).catch((e) => bad("Check failed: " + e.message));
})();
